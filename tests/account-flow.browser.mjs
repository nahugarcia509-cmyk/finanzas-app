import assert from 'node:assert/strict'
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright')
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || '/usr/bin/chromium', headless: true })
try {
  const page = await browser.newPage({ timezoneId: 'America/Argentina/Buenos_Aires' })
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.clock.setFixedTime(new Date('2026-11-10T01:00:00Z'))
  await page.goto(process.env.APP_URL || 'http://127.0.0.1:5173')
  // This browser context is disposable; it never uses the user's stored data.
  await page.evaluate(() => {
    localStorage.clear()
    localStorage.setItem('finance_accounts_demo', JSON.stringify([
      { id: 'mp', name: 'Mercado Pago', initial_balance: 2268573.1 },
      { id: 's', name: 'Santander', initial_balance: 0 }
    ]))
    localStorage.setItem('finance_categories', JSON.stringify([{ id: 'exp', name: 'Comida', type: 'expense' }, { id: 'inc', name: 'Sueldo', type: 'income' }]))
    localStorage.setItem('finance_demo', '[]')
    localStorage.setItem('finance_primary_account_demo', 's')
    localStorage.setItem('finance_user_settings_demo', JSON.stringify({ opening_balance_month: '2026-10', opening_balance_amount: 2268573.1 }))
  })
  const accounts = async () => page.getByRole('button', { name: 'Gestión de cuentas', exact: true }).click()
  const card = name => page.locator('.account-card').filter({ hasText: name }).locator('strong')
  const amounts = async (mp, bank) => {
    assert.equal(await card('Mercado Pago').innerText(), mp)
    assert.equal(await card('Santander').innerText(), bank)
  }
  await page.reload()
  await accounts()
  const transfer = page.locator('form').filter({ has: page.getByRole('heading', { name: 'Transferencia entre cuentas' }) })
  await transfer.getByLabel(/^Desde/).selectOption('mp')
  await transfer.getByLabel(/^Hacia/).selectOption('s')
  assert.equal(await transfer.getByLabel('Fecha', { exact: true }).inputValue(), '2026-11-09')
  await transfer.getByLabel('Fecha', { exact: true }).fill('2026-11-10')
  await transfer.getByLabel('Monto', { exact: true }).fill('2268573.10')
  await transfer.getByRole('button', { name: 'Transferir', exact: true }).click()
  await amounts('$ 0', '$ 2.268.573,1')
  await page.reload()
  await accounts()
  await amounts('$ 0', '$ 2.268.573,1')
  // A new expense must debit the selected account in every view.
  await page.getByRole('button', { name: 'Egreso', exact: true }).click()
  const modal = page.locator('.modal')
  assert.equal(await modal.getByLabel(/^Cuenta/).inputValue(), 's')
  assert.equal(await modal.getByLabel('Fecha', { exact: true }).inputValue(), '2026-11-09')
  await modal.getByLabel('Monto', { exact: true }).fill('1000')
  await modal.getByLabel('Concepto').fill('Compra en Santander')
  await modal.getByRole('button', { name: 'Guardar egreso', exact: true }).click()
  await amounts('$ 0', '$ 2.267.573,1')
  await page.getByRole('button', { name: 'Egresos', exact: true }).click()
  await page.getByTitle('Edición completa', { exact: true }).first().click()
  await modal.getByLabel(/^Cuenta/).selectOption('mp')
  await modal.getByLabel('Monto', { exact: true }).fill('500')
  await modal.getByRole('button', { name: 'Guardar egreso', exact: true }).click()
  await accounts()
  await amounts('-$ 500', '$ 2.268.573,1')
  await page.getByRole('button', { name: 'Egresos', exact: true }).click()
  await page.getByTitle('Edición completa', { exact: true }).first().click()
  await modal.getByLabel(/^Cuenta/).selectOption('s')
  await modal.getByLabel('Monto', { exact: true }).fill('1000')
  await modal.getByRole('button', { name: 'Guardar egreso', exact: true }).click()
  await page.getByPlaceholder('Buscar egresos...').fill('sin coincidencias')
  await page.getByRole('button', { name: 'INICIO', exact: true }).click()
  assert.match(await page.locator('.kpi-info-card').filter({ hasText: 'Saldo actual' }).first().locator('strong').innerText(), /2\.267\.573,1/)
  await accounts()
  await amounts('$ 0', '$ 2.267.573,1')
  await page.getByRole('combobox', { name: 'Cuenta principal', exact: true }).selectOption('mp')
  await amounts('$ 0', '$ 2.267.573,1')
  await page.getByRole('button', { name: 'INICIO', exact: true }).click()
  assert.match(await page.locator('.kpi-info-card').filter({ hasText: 'Saldo actual' }).first().locator('strong').innerText(), /2\.267\.573,1/)
  await page.reload()
  await accounts()
  await amounts('$ 0', '$ 2.267.573,1')
  // Remove both transfer entries; only the actual expense remains.
  await page.getByRole('button', { name: /Eliminar transferencia Transferencia de/ }).click()
  await page.getByRole('button', { name: 'Eliminar transferencia', exact: true }).click()
  await amounts('$ 2.268.573,1', '-$ 1.000')
  assert.deepEqual(errors, [])
  console.log('PASS: fecha local, transferencia total MP→Santander, recarga, gasto en Santander, balance de Inicio, cambio de principal y eliminación de ambas partes de la transferencia.')
} finally {
  await browser.close()
}
